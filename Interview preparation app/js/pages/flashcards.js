function renderFlashcards() {
  if (flashcardState.loading) return renderFlashcardsLoading();
  if (flashcardState.cards.length > 0 && !flashcardState.sessionComplete) return renderFlashcardSession();
  if (flashcardState.sessionComplete) return renderFlashcardSummary();
  return renderFlashcardSetup();
}

