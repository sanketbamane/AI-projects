let flashCardCount = 5;

function selectFlashcardTopic(topic, el) {
  document.querySelectorAll('#topic-tags .tag').forEach(t => t.classList.remove('active'));
  el.classList.add('active');
  flashcardState.topic = topic;
  const custom = document.getElementById('custom-topic');
  if (custom) custom.value = '';
}

function setCustomTopic(val) {
  if (val) {
    document.querySelectorAll('#topic-tags .tag').forEach(t => t.classList.remove('active'));
    flashcardState.topic = val;
  }
}

function setFlashDiff(btn, diff) {
  btn.parentElement.querySelectorAll('.tab').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');
  flashcardState.difficulty = diff;
}

function setFlashCount(btn, count) {
  document.querySelectorAll('#fcard-5,#fcard-8,#fcard-10').forEach(b => b.classList.remove('active'));
  btn.classList.add('active');
  flashCardCount = count;
}

async function generateFlashcards() {
  const topic = flashcardState.topic || document.getElementById('custom-topic')?.value?.trim();
  if (!topic) { showToast('Please select or enter a topic', 'error'); return; }
  if (!Storage.getApiKey()) { showToast('Add a Gemini API key in Settings first', 'error'); return; }

  flashcardState.topic = topic;
  flashcardState.loading = true;
  flashcardState.cards = [];
  flashcardState.currentIndex = 0;
  flashcardState.flipped = false;
  flashcardState.sessionKnown = [];
  flashcardState.sessionPractice = [];
  flashcardState.sessionComplete = false;
  renderPage('flashcards');

  try {
    const cards = await Gemini.generateFlashcards(topic, flashCardCount, flashcardState.difficulty);
    flashcardState.cards = cards;
    flashcardState.loading = false;
    Storage.logActivity();
    renderPage('flashcards');
  } catch (e) {
    flashcardState.loading = false;
    showToast('Failed to generate cards: ' + e.message, 'error');

    // Fallback to static questions if available
    const category = Object.keys(QUESTIONS_BANK).find(k =>
      topic.toLowerCase().includes(k.toLowerCase()) || k.toLowerCase().includes(topic.toLowerCase().split(' ')[0])
    );
    if (category) {
      flashcardState.cards = QUESTIONS_BANK[category].slice(0, flashCardCount);
      showToast('Using offline question bank as fallback', 'success');
      renderPage('flashcards');
    } else {
      renderPage('flashcards');
    }
  }
}

